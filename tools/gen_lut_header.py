#!/usr/bin/env python3
"""Generate hls/common/activation_lut_contents.h from the integer oracle.

The generated header carries the INT16 sigmoid and tanh tables exactly as
model/integer_oracle/oracle.py computes them (banker's rounding of the double
formula over the full Q7.10 input range).  A pytest check regenerates the
file and asserts bit-equality, so the artifact must never be hand-edited.

Usage: python3 tools/gen_lut_header.py
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "model" / "integer_oracle"))

import oracle  # noqa: E402  (local single-source-of-truth module)

OUT = ROOT / "hls" / "common" / "activation_lut_contents.h"

N = 65536  # Q7.10 index range: -32768 .. 32767


def build_table(fn) -> list[int]:
    """Evaluate the builder over [-32768, 32767]; result must stay INT16."""
    out = [0] * N
    for i in range(-32768, 32768):
        v = fn(i)
        assert -32768 <= v <= 32767, (i, v)
        out[i + 32768] = v
    return out


def fmt_table(name: str, vals: list[int]) -> str:
    lines = [f"static const int16_t {name}[{N}] = {{"]
    for i in range(0, N, 8):
        lines.append("  " + ", ".join(f"{v:6d}" for v in vals[i:i + 8]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main() -> int:
    sig = build_table(oracle.sigmoid_q15)
    tan = build_table(oracle.tanh_q15)

    body = "\n".join(
        [
            "// Generated by tools/gen_lut_header.py from model/integer_oracle/oracle.py.",
            "// DO NOT EDIT BY HAND - regeneration is checked bit-identically by tests/.",
            "// Q7.10 signed input (index + 32768) -> Q1.15 INT16 output.",
            "#ifndef MGR1_ACTIVATION_LUT_CONTENTS_H",
            "#define MGR1_ACTIVATION_LUT_CONTENTS_H",
            "",
            fmt_table("MGR1_SIGMOID_LUT", sig),
            "",
            fmt_table("MGR1_TANH_LUT", tan),
            "",
            "#endif  // MGR1_ACTIVATION_LUT_CONTENTS_H",
            "",
        ]
    )

    OUT.write_text(body, encoding="utf-8")

    # Boundary witnesses, matching docs/03-integer-contract.md.
    assert sig[32768 + 0] == 16384
    assert sig[32768 + 32767] == 32767  # upper tail saturates to Q15_ONE
    assert sig[0] >= 0 and sig[0] <= 4  # lower tail collapses toward zero
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
