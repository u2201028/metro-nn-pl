#!/usr/bin/env python3
"""Generate hls/common/cascade_config.h from the frozen worksheet graph.

The MobileNetV2 backbone (stem + 16 inverted-residual blocks + final 1x1)
is described by tools/worksheet.py conv_layers(); this generator turns that
single description into compile-time constants for the dataflow cascade in
hls/mnv2_features/cascade_engine.hpp.  Regeneration is deterministic and
idempotent; never hand-edit the generated header (see the DO NOT EDIT
banner and tests/test_cascade_config.py).
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))

from worksheet import conv_layers  # noqa: E402

OUT = ROOT / "hls" / "common" / "cascade_config.h"


def main() -> int:
    layers = conv_layers()
    lines = [
        "// Generated by tools/gen_cascade_config.py - DO NOT EDIT BY HAND.",
        "// One entry per frozen graph node: op kind, cin, cout, k, s, pad.",
        "// The dataflow cascade (hls/mnv2_features/cascade_engine.hpp)",
        "// instantiates one engine per entry, in this exact order.",
        "",
        "#ifndef MGR1_CASCADE_CONFIG_H",
        "#define MGR1_CASCADE_CONFIG_H",
        "",
        "#define MGR1_CASCADE_DEPTH {}".format(len(layers)),
        "",
        "namespace mgr1 {",
        "",
        "enum CascadeOp : unsigned char { OP_CONV3X3 = 0, OP_CONV1X1 = 1, OP_DW3X3 = 2 };",
        "",
        "struct CascadeNode {",
        "    unsigned char op;",
        "    short cin;",
        "    short cout;",
        "    short k;",
        "    short s;",
        "    short pad;",
        "};",
        "",
        "static const CascadeNode kCascade[MGR1_CASCADE_DEPTH] = {",
    ]
    for L in layers:
        k, s = L["k"], L["stride"]
        pad = 1 if L["kind"] in ("conv3x3", "dw3x3") else 0
        op = {"conv3x3": "OP_CONV3X3", "conv1x1": "OP_CONV1X1",
              "dw3x3": "OP_DW3X3"}[L["kind"]]
        lines.append(
            f'    {{ {op}, {L["cin"]:>4}, {L["cout"]:>4}, {k}, {s}, {pad} }},'
            f'  // {L["name"]}'
        )
    lines += [
        "};",
        "",
        "}  // namespace mgr1",
        "",
        "#endif  // MGR1_CASCADE_CONFIG_H",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({len(layers)} nodes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
